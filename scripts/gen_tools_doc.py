#!/usr/bin/env python3
"""Generate ``docs/TOOLS.md`` from every desk tool's ``--schema`` answer and parser. Stdlib only; no network.

The tools come only from the literal import statements below (``TOOL_MODULES``, sorted by name); a computed
import would fail the repository's AST gate. For each tool the generator calls ``main(["--schema"])`` in-process
with stdout captured and parses the JSON it prints, and reads the flags from
``build_parser(release_version())._actions`` (option strings or the positional's name, metavar, choices, nargs and
help), never from the formatted help, whose wrapping depends on the terminal width. Nothing depends on the clock,
the terminal or the interpreter, so the output is byte-identical on Python 3.9 to 3.13.

``docs/TOOLS.md`` holds the title, the line ``HEADER``, the envelope keys, the error-envelope keys and the
exit-code table that every tool shares (a tool whose envelope, error shape or exit codes differ is an error: the
contract has one table), then one ``## <tool>`` section per tool: the script path, tool version, mode,
description and network access, a flags table (a pipe inside a cell is written ``\\|``), one line per top-level
payload key with ``json.dumps(value, sort_keys=True)``, and the ``input`` key of the ``--schema`` answer when a
tool declares one (``desk_init``). A ``--schema`` key the generator does not know is an error, so a new key is a
reviewed change here.

``--check`` renders in memory and exits 1 with the first ``DIFF_LINES`` lines of a unified diff when the committed
file differs, or with one line when it is missing. Both modes also fail when a ``scripts/*.py`` file defines both
a ``build_parser(`` and a ``main(`` function but is missing from ``TOOL_MODULES``. Paths come from this script's
own location (``SCRIPTS_DIR``, ``DOC_PATH``; the tests patch them), so ``check.sh`` step 9 checks the tree it
runs in.

Usage: ``python3 scripts/gen_tools_doc.py [--check]``. Exit 0 written or current, 1 drift or error, 2 usage.
"""
from __future__ import annotations

import argparse
import ast
import contextlib
import difflib
import io
import json
import os
import sys
from typing import Any, Dict, List, Optional, Sequence, Tuple

from aegis_desk import version

import ack
import alert_lint
import assignment_watch
import book
import book_check
import calendar_check
import csv_recon
import desk_doctor
import desk_init
import eod_summary
import exit_check
import exit_ticket
import expiry_checklist
import heartbeat
import market_clock
import opening_bell
import positions_check
import propose
import quote_cache
import quote_qc
import roll_analysis
import routine
import routine_audit
import rules_adopt
import rules_diff
