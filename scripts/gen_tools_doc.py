TOOL_MODULES = (
    ack, alert_lint, assignment_watch, book, book_check, calendar_check, csv_recon, desk_doctor, desk_init,
    eod_summary, exit_check, exit_ticket, expiry_checklist, heartbeat, market_clock, opening_bell, positions_check,
    propose, quote_cache, quote_qc, roll_analysis, routine, routine_audit, rules_adopt, rules_diff, trigger_levels,
)
"""Every desk tool (a ``scripts/*.py`` with ``build_parser`` and ``main``), sorted by name."""

SCRIPTS_DIR = os.path.dirname(os.path.abspath(__file__))
ROOT = os.path.dirname(SCRIPTS_DIR)
DOC_REL = "docs/TOOLS.md"
DOC_PATH = os.path.join(ROOT, "docs", "TOOLS.md")
TITLE = "# Desk tools"
HEADER = "Generated by scripts/gen_tools_doc.py from each tool's --schema; do not edit by hand."
DIFF_LINES = 40
REGENERATE = "run python3 scripts/gen_tools_doc.py"
SCHEMA_KEYS = ("description", "envelope", "error", "exit_codes", "mode", "network_access", "schema_version", "tool",
               "tool_version")
OPTIONAL_SCHEMA_KEYS = ("input",)
PER_TOOL_KEYS = ("payload", "tool", "tool_version")
"""Envelope and error keys whose value differs per tool; every other key is shared by the whole contract."""
NARGS_WORDS = {"?": "optional", "*": "zero or more", "+": "one or more"}
TOOL_FUNCTIONS = ("build_parser", "main")
"""A ``scripts/*.py`` that defines both at its top level (read by AST, never imported) is a tool."""


class GenError(Exception):
    """The generator cannot render: a tool's ``--schema`` failed, or the tools disagree on a shared shape."""


def fold(text: Any) -> str:
    """``text`` on one line: every run of whitespace, newlines included, becomes one space."""
    return " ".join(str(text).split())


def cell(text: Any) -> str:
    """``text`` as one Markdown table cell: folded onto one line, a pipe written as ``\\|``."""
    return fold(text).replace("|", "\\|")


def span(text: str) -> str:
    """``text`` as an inline code span (a longer fence when the text holds a backtick)."""
    if "`" in text:
        return "`` %s ``" % text
    return "`%s`" % text


def tool_schema(module: Any) -> Dict[str, Any]:
    """The JSON object ``module.main(["--schema"])`` prints; ``GenError`` when it exits non-zero or prints no JSON."""
    out, err = io.StringIO(), io.StringIO()
    name = getattr(module, "__name__", "?")
    with contextlib.redirect_stdout(out), contextlib.redirect_stderr(err):
        try:
            status = module.main(["--schema"])
        except SystemExit as exc:
            status = exc.code
    if status not in (0, None):
        raise GenError("%s --schema exited %s: %s" % (name, status, fold(err.getvalue() or out.getvalue())[:200]))
    try:
        schema = json.loads(out.getvalue())
    except ValueError as exc:
        raise GenError("%s --schema printed no JSON object: %s" % (name, exc)) from None
    if not isinstance(schema, dict):
        raise GenError("%s --schema printed %s, not a JSON object" % (name, type(schema).__name__))
    unknown = sorted(set(schema) - set(SCHEMA_KEYS) - set(OPTIONAL_SCHEMA_KEYS))
    missing = sorted(set(SCHEMA_KEYS) - set(schema))
    if unknown or missing:
        raise GenError("%s --schema keys differ from the contract (unknown %s, missing %s); update gen_tools_doc.py"
                       % (name, unknown or "none", missing or "none"))
    if schema["tool"] != name:
        raise GenError("scripts/%s.py names its tool %r in --schema" % (name, schema["tool"]))
    return schema


def expand_help(action: argparse.Action, prog: str) -> str:
    """The help text as argparse would print it: ``%(default)s`` and friends expanded, ``%%`` as ``%``."""
    text = action.help or ""
    if "%" not in text:
        return text
    params = dict(vars(action), prog=prog)
    for key in list(params):
        if params[key] is argparse.SUPPRESS:
            del params[key]
        elif hasattr(params[key], "__name__"):
            params[key] = params[key].__name__
    if params.get("choices") is not None:
        params["choices"] = ", ".join(str(choice) for choice in params["choices"])
    return text % params


def flag_value(action: argparse.Action) -> str:
    """The value column: ``none`` for a switch, else the choices, the metavar or the name, with its count."""
    if action.nargs == 0:
        return "none"
    if action.choices is not None:
        base = " | ".join(str(choice) for choice in action.choices)
    elif action.metavar is not None:
        base = " ".join(action.metavar) if isinstance(action.metavar, tuple) else str(action.metavar)
    elif action.option_strings:
        base = action.dest.upper()
    else:
        base = action.dest
    text = span(cell(base))
    if isinstance(action.nargs, int):
        text += " (exactly %d)" % action.nargs
    elif action.nargs in NARGS_WORDS:
        text += " (%s)" % NARGS_WORDS[action.nargs]
    return text


def flag_rows(parser: argparse.ArgumentParser) -> List[Tuple[str, str, str]]:
    """One ``(flag, value, help)`` row per argument the parser declares, in declaration order."""
    rows = []
    for action in parser._actions:
        if action.help is argparse.SUPPRESS:
            continue
        if action.option_strings:
            flag = ", ".join(span(option) for option in action.option_strings)
            if action.required:
                flag += " (required)"
        else:
            flag = "%s (positional)" % span(action.dest)
        rows.append((flag, flag_value(action), cell(expand_help(action, parser.prog)) or "(no help text)"))
    return rows


def shared_shape(schema: Dict[str, Any]) -> Tuple[Dict[str, Any], Dict[str, Any], Dict[str, Any]]:
    """``(envelope, error, exit codes)`` of one tool without the keys that differ per tool."""
    envelope = {key: value for key, value in schema["envelope"].items() if key not in PER_TOOL_KEYS}
    error = {key: value for key, value in schema["error"].items() if key not in PER_TOOL_KEYS}
    return envelope, error, schema["exit_codes"]


def key_lines(document: Any) -> List[str]:
    """One ``- `key`: `json`` line per top-level key, sorted; a non-object is one line of JSON."""
    if not isinstance(document, dict):
        return ["- %s" % span(json.dumps(document, sort_keys=True))]
    return ["- %s: %s" % (span(key), span(json.dumps(document[key], sort_keys=True))) for key in sorted(document)]


def render(modules: Optional[Sequence[Any]] = None) -> str:
    """The whole ``docs/TOOLS.md`` text (``GenError`` when a tool cannot be rendered)."""
    modules = TOOL_MODULES if modules is None else tuple(modules)
    release = version.release_version()
    schemas = [(module, tool_schema(module)) for module in modules]
    shapes = {json.dumps(shared_shape(schema), sort_keys=True) for _module, schema in schemas}
    if len(shapes) != 1:
        odd = [module.__name__ for module, schema in schemas
               if json.dumps(shared_shape(schema), sort_keys=True) != json.dumps(shared_shape(schemas[0][1]),
                                                                                  sort_keys=True)]
        raise GenError("the tools do not share one envelope, error shape and exit-code table: %s differ from %s"
                       % (", ".join(odd), schemas[0][0].__name__))
    envelope, error, exit_codes = shared_shape(schemas[0][1])
    lines = [TITLE, "", HEADER, "",
             "Every tool prints one JSON envelope with `--json` and describes it with `--schema` (no network, no "
             "desk file). The envelope keys every tool shares, besides `tool`, `tool_version` and its own "
             "`payload`:", ""]
    lines += key_lines(envelope)
    lines += ["", "The error envelope (status `error`, `usage` or `unavailable`), besides `tool` and `tool_version`:",
              ""]
    lines += key_lines(error)
    lines += ["", "One exit-code table for every tool:", "", "| Exit code | Meaning |", "| --- | --- |"]
    lines += ["| %s | %s |" % (exit_code, cell(exit_codes[exit_code]))
              for exit_code in sorted(exit_codes, key=int)]
    for module, schema in sorted(schemas, key=lambda item: item[0].__name__):
        name = module.__name__
        lines += ["", "## %s" % name, "",
                  "- script: `scripts/%s.py`" % name,
                  "- tool version: %s" % fold(schema["tool_version"]),
                  "- mode: %s" % fold(schema["mode"]),
                  "- description: %s" % fold(schema["description"]),
                  "- network access: %s" % fold(schema["network_access"]),
                  "", "| Flag | Value | Help |", "| --- | --- | --- |"]
        lines += ["| %s | %s | %s |" % row for row in flag_rows(module.build_parser(release))]
        lines += ["", "Payload (`--json` envelope key `payload`):", ""]
        lines += key_lines(schema["envelope"]["payload"])
        if "input" in schema:
            lines += ["", "Input (`--schema` key `input`):", ""]
            lines += key_lines(schema["input"])
    return "\n".join(lines) + "\n"


def top_level_functions(source: str) -> List[str]:
    """The names of the module-level ``def`` statements of ``source`` (``[]`` when it does not parse: the gates report
    that file)."""
    try:
        tree = ast.parse(source)
    except SyntaxError:
        return []
    return [node.name for node in tree.body if isinstance(node, (ast.FunctionDef, ast.AsyncFunctionDef))]


def unlisted_tools(scripts_dir: Optional[str] = None, modules: Optional[Sequence[Any]] = None) -> List[str]:
    """``scripts/<name>.py`` for every file whose top level defines ``build_parser`` and ``main`` (by AST: spacing, a
    docstring or a nested function cannot hide or fake one) but is not listed."""
    scripts_dir = SCRIPTS_DIR if scripts_dir is None else scripts_dir
    listed = {module.__name__ for module in (TOOL_MODULES if modules is None else modules)}
    found = []
    for name in sorted(os.listdir(scripts_dir)):
        if not name.endswith(".py") or name[:-3] in listed:
            continue
        with open(os.path.join(scripts_dir, name), encoding="utf-8") as handle:
            defined = top_level_functions(handle.read())
        if all(function in defined for function in TOOL_FUNCTIONS):
            found.append("scripts/%s" % name)
    return found


def unlisted_errors() -> List[str]:
    return ["error: %s defines build_parser() and main() but is missing from TOOL_MODULES; import it in "
            "scripts/gen_tools_doc.py" % rel for rel in unlisted_tools()]


def check() -> Tuple[int, List[str]]:
    """``(exit code, lines)`` of ``--check``: the committed file against the rendering, nothing written."""
    errors = unlisted_errors()
    if errors:
        return 1, errors
    text = render()
    if not os.path.isfile(DOC_PATH):
        return 1, ["error: %s is missing; %s" % (DOC_REL, REGENERATE)]
    with open(DOC_PATH, encoding="utf-8") as handle:
        current = handle.read()
    if current == text:
        return 0, ["ok: %s matches the --schema of %d tools" % (DOC_REL, len(TOOL_MODULES))]
    diff = difflib.unified_diff(current.splitlines(), text.splitlines(), DOC_REL, DOC_REL + " (rendered)", lineterm="")
    return 1, ["error: %s is out of date; %s" % (DOC_REL, REGENERATE)] + list(diff)[:DIFF_LINES]


def write() -> Tuple[int, List[str]]:
    """``(exit code, lines)`` of the default mode: render and write ``docs/TOOLS.md``."""
    errors = unlisted_errors()
    if errors:
        return 1, errors
    text = render()
    with open(DOC_PATH, "w", encoding="utf-8", newline="\n") as handle:
        handle.write(text)
    return 0, ["wrote %s (%d tools)" % (DOC_REL, len(TOOL_MODULES))]


def make_parser() -> argparse.ArgumentParser:
    parser = argparse.ArgumentParser(prog="gen_tools_doc.py", description=__doc__.splitlines()[0])
    parser.add_argument("--check", action="store_true",
                        help="render in memory and fail on drift instead of writing docs/TOOLS.md")
    return parser


def main(argv: Optional[Sequence[str]] = None) -> int:
    args = make_parser().parse_args(argv)
    try:
        status, lines = check() if args.check else write()
    except (GenError, OSError) as exc:
        status, lines = 1, ["error: %s" % exc]
    for line in lines:
        print(line)
    return status


if __name__ == "__main__":
    sys.exit(main())
